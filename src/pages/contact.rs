/// The recognized mark for one identity, keyed by its cv.toml label.
///
/// ORCID, GitHub, Hugging Face, `YouTube`, and Scopus use their
/// simple-icons paths; the Web of Science `ResearcherID` uses
/// Clarivate's mark (Web of Science is Clarivate's service and has
/// no mark of its own there). Loop, `SciProfiles`, and Authenticus
/// have no simple-icons mark, so they carry each service's own
/// favicon, self-hosted under public/img/icons/: Frontiers'
/// concentric-target glyph for Loop, MDPI's "Sci" bubble for
/// `SciProfiles`, and Authenticus' "a" ring. Every icon is
/// decorative — the label beside it carries the name.
fn identity_icon(label: &str) -> AnyView {
    match label {
        "AuthenticusID" => view! {
            <img
                class="cv-id-icon"
                src="/img/icons/authenticus.png"
                alt=""
                aria-hidden="true"
            />
        }
        .into_any(),
        "Loop profile" => view! {
            <img
                class="cv-id-icon"
                src="/img/icons/loop.png"
                alt=""
                aria-hidden="true"
            />
        }
        .into_any(),
        "SciProfiles" => view! {
            <img
                class="cv-id-icon"
                src="/img/icons/sciprofiles.png"
                alt=""
                aria-hidden="true"
            />
        }
        .into_any(),
        _ => {
            let path = match label {
                "GitHub" => ICON_GITHUB,
                "Hugging Face" => ICON_HUGGINGFACE,
                "ORCID" => ICON_ORCID,
                "ResearcherID (Web of Science)" => ICON_CLARIVATE,
                "Scopus Author ID" => ICON_SCOPUS,
                "YouTube" => ICON_YOUTUBE,
                _ => "",
            };
            view! {
                <svg
                    class="cv-id-icon"
                    viewBox="0 0 24 24"
                    fill="currentColor"
                    aria-hidden="true"
                >
                    <path d={path} />
                </svg>
            }
            .into_any()
        }
    }
}

