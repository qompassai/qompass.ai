/// Anchor slug for a glossary term: lowercase ASCII alphanumerics,
/// everything else collapsed to single hyphens.
fn term_slug(term: &str) -> String {
    let mut slug = String::new();
    for c in term.chars() {
        if c.is_ascii_alphanumeric() {
            slug.push(c.to_ascii_lowercase());
        } else if !slug.ends_with('-') && !slug.is_empty() {
            slug.push('-');
        }
    }
    slug.trim_end_matches('-').to_string()
}

/// Legend labels are injected as HTML, so they may carry only the
/// typographic tags the generator's authors use: italics, sub, sup.
fn check_label(label: &str) -> Result<(), String> {
    let mut rest = label;
    while let Some(start) = rest.find('<') {
        let end = rest[start..].find('>').ok_or_else(|| format!("unclosed tag in legend label {label:?}"))?;
        let tag = &rest[start..=start + end];
        if !["<i>", "</i>", "<sub>", "</sub>", "<sup>", "</sup>"].contains(&tag) {
            return Err(format!("tag {tag} not allowed in legend label {label:?}"));
        }
        rest = &rest[start + end + 1..];
    }
    Ok(())
}

/// Emit `field_notes_data.rs` from `content/field-notes/`.
///
/// Quizzes are the source repo's practice sets, copied byte-for-byte
/// (see `content/field-notes/quizzes.toml`); the build refuses a set
/// whose answer does not match exactly one of its choices. The glossary
/// and its equations come from `glossary.json` and the committed
/// renderings in `equations.json` (scripts/generate-field-notes-
/// equations.cjs); the build refuses a mismatch between the two.
fn emit_field_notes() -> Result<(), Box<dyn std::error::Error>> {
    println!("cargo:rerun-if-changed=content/field-notes");
    let base = std::path::Path::new("content/field-notes");
    let order: QuizOrder = toml::from_str(&std::fs::read_to_string(base.join("quizzes.toml"))?)?;
    let mut on_disk: Vec<String> = std::fs::read_dir(base.join("quizzes"))?
        .flatten()
        .filter_map(|e| e.file_name().into_string().ok())
        .filter(|name| std::path::Path::new(name).extension().is_some_and(|ext| ext == "json"))
        .collect();
    on_disk.sort();
    let mut listed = order.order.clone();
    listed.sort();
    if listed != on_disk {
        return Err(format!("quizzes.toml order {listed:?} does not list exactly the quiz files {on_disk:?}").into());
    }

    let mut out = String::new();
    out.push_str("// Generated by build.rs from content/field-notes — do not edit.\n");
    out.push_str(
        "pub struct QuizQuestion { pub number: u32, pub prompt: &'static str, pub choices: &'static [&'static str], pub answer: usize, pub explanation: &'static str, pub sections: &'static [&'static str], pub index_paths: &'static [&'static str], pub choice_notes: &'static [&'static str] }\n\
         pub struct Quiz { pub slug: &'static str, pub title: &'static str, pub description: &'static str, pub questions: &'static [QuizQuestion] }\n",
    );
    out.push_str("pub static QUIZZES: &[Quiz] = &[");
    for name in &order.order {
        let file: QuizFile = serde_json::from_str(&std::fs::read_to_string(base.join("quizzes").join(name))?)?;
        let _ = write!(
            out,
            "Quiz {{ slug: {}, title: {}, description: {}, questions: &[",
            lit(&file.id),
            lit(&file.title),
            lit(&file.description)
        );
        for q in &file.questions {
            let matches: Vec<usize> =
                q.choices.iter().enumerate().filter(|(_, c)| **c == q.answer).map(|(i, _)| i).collect();
            let [answer] = matches.as_slice() else {
                return Err(format!("{name} question {}: answer matches {} choices", q.id, matches.len()).into());
            };
            let (explanation, sections, index_paths, notes) = match &q.explanation {
                QuizExplanation::Plain(text) => (text.clone(), Vec::new(), Vec::new(), Vec::new()),
                QuizExplanation::Rich { correct, choices } => {
                    let mut notes = Vec::new();
                    for choice in &q.choices {
                        let part = choices
                            .get(choice)
                            .ok_or_else(|| format!("{name} question {}: no note for choice {choice:?}", q.id))?;
                        notes.push(if part.sections.is_empty() {
                            part.text.clone()
                        } else {
                            format!("{} ({})", part.text, part.sections.join(", "))
                        });
                    }
                    (correct.text.clone(), correct.sections.clone(), correct.index_keywords.clone(), notes)
                }
            };
            let _ = write!(
                out,
                "QuizQuestion {{ number: {}, prompt: {}, choices: {}, answer: {answer}, explanation: {}, sections: {}, index_paths: {}, choice_notes: {} }},",
                q.id,
                lit(&q.question),
                lit_list(&q.choices),
                lit(&explanation),
                lit_list(&sections),
                lit_list(&index_paths),
                lit_list(&notes)
            );
        }
        out.push_str("] },");
    }
    out.push_str("];\n");

    let glossary: GlossaryFile = serde_json::from_str(&std::fs::read_to_string(base.join("glossary.json"))?)?;
    let rendered: EquationsFile = serde_json::from_str(&std::fs::read_to_string(base.join("equations.json"))?)?;
    let authored = glossary.terms.iter().map(|t| t.equations.len()).sum::<usize>();
    if authored != rendered.count || rendered.equations.len() != rendered.count {
        return Err(format!(
            "glossary.json has {authored} equations, equations.json {} ({} rendered): rerun scripts/generate-field-notes-equations.cjs",
            rendered.count,
            rendered.equations.len()
        )
        .into());
    }
    out.push_str(
        "pub struct GlossaryEquation { pub id: &'static str, pub tex: &'static str, pub svg: &'static str, pub plain: &'static str, pub legend: &'static [(&'static str, &'static str)] }\n\
         pub struct GlossaryTerm { pub term: &'static str, pub slug: &'static str, pub definition: &'static str, pub equations: &'static [GlossaryEquation] }\n",
    );
    let _ = writeln!(out, "pub static EQUATION_DEFS: &str = {};", lit(&rendered.defs));
    out.push_str("pub static GLOSSARY: &[GlossaryTerm] = &[");
    for t in &glossary.terms {
        if t.definition.contains('<') {
            return Err(format!("glossary term {:?}: definitions are plain text", t.term).into());
        }
        let _ = write!(
            out,
            "GlossaryTerm {{ term: {}, slug: {}, definition: {}, equations: &[",
            lit(&t.term),
            lit(&term_slug(&t.term)),
            lit(&t.definition)
        );
        for e in &t.equations {
            let r = rendered.equations.get(&e.id).ok_or_else(|| format!("equation {} has no rendering", e.id))?;
            if !r.svg.starts_with("<svg ") || r.svg.contains("<script") || r.svg.contains("<style") {
                return Err(format!("equation {}: rendering is not a plain SVG", e.id).into());
            }
            let mut legend = String::from("&[");
            for &i in &r.legend {
                let s = t.symbols.get(i).ok_or_else(|| format!("equation {}: legend index {i} out of range", e.id))?;
                check_label(&s.label)?;
                let _ = write!(legend, "({}, {}),", lit(&s.label), lit(&s.meaning));
            }
            legend.push(']');
            let _ = write!(
                out,
                "GlossaryEquation {{ id: {}, tex: {}, svg: {}, plain: {}, legend: {legend} }},",
                lit(&e.id),
                lit(&e.tex),
                lit(&r.svg),
                lit(&e.plain)
            );
        }
        out.push_str("] },");
    }
    out.push_str("];\n");

    let dest = std::path::Path::new(&std::env::var("OUT_DIR")?).join("field_notes_data.rs");
    std::fs::write(dest, out)?;
    Ok(())
}

