#!/usr/bin/env python3
"""Regenerate src/orcid_data.rs from the live ORCID public record.

Usage: python3 scripts/fetch-orcid.py [orcid-id]
No credentials: the public API serves the public record. Output is sorted
newest first and capped at 100 works. Rust string literals are emitted via
json.dumps, whose escaping is compatible for our content.
"""
import json
import sys
import urllib.request

ORCID = sys.argv[1] if len(sys.argv) > 1 else "0000-0002-0302-4812"
URL = f"https://pub.orcid.org/v3.0/{ORCID}/works"


def fetch(url: str) -> dict:
    req = urllib.request.Request(url, headers={"Accept": "application/json"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.load(resp)


def main() -> int:
    data = fetch(URL)
    works = []
    for group in data.get("group", []):
        summaries = group.get("work-summary") or []
        if not summaries:
            continue
        w = summaries[0]
        title = ((w.get("title") or {}).get("title") or {}).get("value", "").strip()
        if not title:
            continue
        venue = (w.get("journal-title") or {}).get("value", "") or w.get("type", "")
        work_type = w.get("type", "") or ""
        date = w.get("publication-date") or {}
        year = ((date.get("year") or {}).get("value") or "")
        doi = ""
        for ext in w.get("external-ids", {}).get("external-id", []):
            if ext.get("external-id-type") == "doi":
                doi = ext.get("external-id-value", "").strip()
                break
        for prefix in ("https://doi.org/", "http://doi.org/"):
            if doi.startswith(prefix):
                doi = doi[len(prefix):]
                break
        url = (w.get("url") or {}).get("value", "") or ""
        if not url:
            for ext in w.get("external-ids", {}).get("external-id", []):
                if ext.get("external-id-type") == "doi":
                    url = "https://doi.org/" + ext.get("external-id-value", "")
                    break
        if not url:
            url = f"https://orcid.org/{ORCID}"
        if not doi:
            for prefix in ("https://doi.org/", "http://doi.org/"):
                if url.startswith(prefix):
                    doi = url[len(prefix):]
                    break
        works.append(
            {
                "title": title,
                "venue": venue,
                "year": year,
                "url": url,
                "doi": doi,
                "kind": work_type,
            }
        )
    works.sort(key=lambda x: x["year"], reverse=True)
    works = works[:100]

    lines = [
        "// ORCID works snapshot — regenerated by scripts/fetch-orcid.py at build time.",
        "// The Research page renders this list as its no-JS baseline; /js/orcid.js then",
        "// refreshes it live from the ORCID public API in the browser.",
        "pub struct Work {",
        "    pub title: &'static str,",
        "    pub url: &'static str,",
        "    pub venue: &'static str,",
        "    pub year: &'static str,",
        "    pub doi: &'static str,",
        "    pub kind: &'static str,",
        "}",
        "",
        "pub static WORKS: &[Work] = &[",
    ]
    for w in works:
        lines.append("    Work {")
        lines.append(f"        title: {json.dumps(w['title'], ensure_ascii=False)},")
        lines.append(f"        url: {json.dumps(w['url'], ensure_ascii=False)},")
        lines.append(f"        venue: {json.dumps(w['venue'], ensure_ascii=False)},")
        lines.append(f"        year: {json.dumps(w['year'], ensure_ascii=False)},")
        lines.append(f"        doi: {json.dumps(w['doi'], ensure_ascii=False)},")
        lines.append(f"        kind: {json.dumps(w['kind'], ensure_ascii=False)},")
        lines.append("    },")
    lines.append("];")
    lines.append("")
    out = "\n".join(lines)
    with open("src/orcid_data.rs", "w", encoding="utf-8") as fh:
        fh.write(out)
    print(f"wrote src/orcid_data.rs with {len(works)} works from ORCID {ORCID}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
