#!/usr/bin/env python3
"""generate-manuscript-data.py — regenerate src/manuscript_data.rs.

Reads the Odyssey manuscripts rollup (default: the primo Odyssey mirror,
Odyssey/manuscripts/rollup.json) and emits the build-time snapshot the
Research page tracker renders. The rollup is generated from each
manuscript's status.json by the Odyssey manuscripts CLI
(manuscripts.py rollup); status.json is the source of truth.

Usage:
  generate-manuscript-data.py [rollup.json] [out.rs]

Defaults: rollup = ~/​.GH/Qompass/Odyssey/manuscripts/rollup.json
          out    = <site root>/src/manuscript_data.rs
"""

import json
import sys
from pathlib import Path

SITE_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_ROLLUP = Path.home() / ".GH/Qompass/Odyssey/manuscripts/rollup.json"
DEFAULT_OUT = SITE_ROOT / "src" / "manuscript_data.rs"

FIELDS = ["slug", "title", "journal_name", "stage", "updated"]


def rust_str(value: str) -> str:
    # The snapshot is a plain Rust string literal: refuse anything that
    # would need escaping rather than emitting a subtly wrong literal.
    if '"' in value or "\\" in value or "\n" in value:
        raise ValueError(f"value is not safe for a plain Rust literal: {value!r}")
    return f'"{value}"'


def main() -> None:
    rollup_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_ROLLUP
    out_path = Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_OUT
    rollup = json.loads(rollup_path.read_text(encoding="utf-8"))
    entries = rollup["manuscripts"]
    if not entries:
        raise SystemExit(f"{rollup_path}: rollup carries no manuscripts")

    lines = [
        "// Odyssey manuscript program snapshot — generated by",
        "// scripts/generate-manuscript-data.py from the Odyssey manuscripts",
        f"// rollup (Odyssey/manuscripts/rollup.json, generated {rollup['generated']}).",
        "// Each manuscript's status.json in its Odyssey sub-repo is the source",
        "// of truth; this list is the build-time snapshot the Research page",
        "// tracker renders. Regenerate after a rollup refresh; do not hand-edit.",
        "pub struct Manuscript {",
        "    pub slug: &'static str,",
        "    pub title: &'static str,",
        "    pub journal_name: &'static str,",
        "    pub stage: &'static str,",
        "    pub updated: &'static str,",
        "}",
        "",
        "pub static MANUSCRIPTS: &[Manuscript] = &[",
    ]
    for entry in entries:
        lines.append("    Manuscript {")
        for field in FIELDS:
            lines.append(f"        {field}: {rust_str(str(entry[field]))},")
        lines.append("    },")
    lines.append("];")
    lines.append("")

    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"manuscript_data: {len(entries)} manuscripts -> {out_path}")


if __name__ == "__main__":
    main()
